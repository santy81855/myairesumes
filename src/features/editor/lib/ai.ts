const getGeneratePrompt = (
    document: any,
    promptId: string,
    jobTitle: string,
    length: number,
    positionTitle: string,
    array: any[]
) => {
    const jobPostPrompt = `Here is the job posting. Use it to understand what the employer cares about and to choose relevant skills and achievements, but do not copy sentences or bullet points from it. Paraphrase everything in your own words. Job description: ${document?.information.jobDescription}`;

    const promptStart = `You are helping a candidate apply for the position of ${jobTitle}. Write in a natural, human resume style: concise, specific, and professional. Use active voice and avoid clichés such as results-driven, detail-oriented, or team player unless they are backed by concrete details.`;

    const promptEnd = `Aim for around ${length} words. Focus on clear, specific impact and avoid generic or overly formal phrasing. Do not mention AI, and do not add any symbols or quotation marks in the output. ${
        document?.information.jobDescription !== "" ? jobPostPrompt : ""
    }`;

    const promptEndCategory = `Keep it concise and at most ${length} words. Make it specific to this role and industry, and avoid generic or buzzword-heavy phrasing. Do not mention AI, and do not add any symbols or quotation marks in the output.`;

    switch (promptId) {
        case "summary":
            return `${promptStart} Write a resume summary for this ${jobTitle} role that highlights the candidate's most relevant experience, strengths, and impact for this position. Use 2–4 concise sentences and avoid repeating the job title unnecessarily. ${promptEnd}`;

        case "experienceSummary":
            return `${promptStart} Write a short highlight summary for the previous role of ${positionTitle}. Emphasize 2–3 of the strongest responsibilities and achievements, prioritizing measurable results (such as percentages, revenue, time saved, or volume) when reasonable. Do not invent company names or dates. ${promptEnd}`;

        case "experienceBullet":
            return `${promptStart} Write one resume bullet point describing a specific responsibility or achievement in the role of ${positionTitle}. Start with a strong action verb and, where possible, include a concrete metric (for example a percentage, dollar amount, or quantity). The current bullet points are: ${array.join(
                ", "
            )}. Do not repeat or rephrase any of these; add a new, distinct bullet that complements them. ${promptEnd}`;

        case "skills":
            return `${promptStart} Suggest one professional skill that would be appropriate to list on a resume for a ${jobTitle}. It should be short, concrete, and specific (for example, “SQL data analysis” rather than “hard-working”). The current skills are: ${array.join(
                ", "
            )}. Do not repeat any of them. ${promptEnd}`;

        case "skillCategory":
            return `${promptStart} Suggest only a skill category name for a ${jobTitle} resume, such as a grouping under which several related skills could be listed. Examples of the style include categories like Technical Skills or Data Analysis, but do not use those exact examples unless they clearly fit. The current categories are: ${array
                .map((obj) => obj.category)
                .join(
                    ", "
                )}. Do not repeat any of them. Return only the category name text, nothing else. ${promptEndCategory}`;

        case "skillCategorySkill":
            return `${promptStart} Suggest one skill that belongs under the category ${
                array[0]
            }. Make it specific and resume-appropriate (for example, “React.js development” rather than just “coding”). The current skills in this category are: ${array
                .slice(1)
                .join(", ")}. Do not repeat any of them. ${promptEnd}`;

        case "body":
            return `${promptStart} Write the main body of a cover letter for the position of ${jobTitle}. Use a confident but approachable tone in the first person, connect the candidate's experience and skills to the needs of the role, and include specific examples of impact. Write in paragraphs and use two newline characters to mark the end of each paragraph. ${promptEnd}`;

        default:
            return "";
    }
};

