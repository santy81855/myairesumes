const getEnhancePrompt = (
    document: any,
    promptId: string,
    jobTitle: string,
    length: number,
    currentText: string,
    positionTitle: string,
    array: any[]
) => {
    const jobPostPrompt = `Here is the job posting. Use it to better align the wording with what the employer is looking for, but do not copy phrases or sentences from it. Paraphrase everything in your own words. Job description: ${document?.information.jobDescription}`;

    const promptStart = `You are helping a candidate apply for the position of ${jobTitle}. Rewrite the text to sound like a polished, human-written resume: concise, specific, and professional. Use active voice and remove filler or clichés unless they are backed by concrete details. Preserve the original meaning.`;

    const promptEnd = `Aim for around ${length} words. Make the wording more natural and impactful while keeping it realistic for a resume. Do not mention AI, and do not add any symbols or quotation marks in the output. ${
        document?.information.jobDescription !== "" ? jobPostPrompt : ""
    }`;

    const promptEndCategory = `Keep it concise and at most ${length} words. Make it specific to this role and industry, and avoid generic or buzzword-heavy phrasing. Do not mention AI, and do not add any symbols or quotation marks in the output.`;

    switch (promptId) {
        case "summary":
            return `${promptStart} Improve the following resume summary so that it is clearer, more specific, and more compelling while keeping the same overall message: ${currentText} ${promptEnd}`;

        case "experienceSummary":
            return `${promptStart} Improve the following highlight summary for the role of ${positionTitle}. Make it more results-focused and professional, and add or clarify quantifiable achievements where reasonable, without inventing unrealistic details: ${currentText} ${promptEnd}`;

        case "experienceBullet":
            return `${promptStart} Rewrite the following resume bullet for the experience section of the role of ${positionTitle}. Make it more action-oriented and focused on impact, and include a concrete metric or outcome if it is implied or reasonable, without fabricating unrealistic claims: ${currentText} ${promptEnd}`;

        case "skills":
            return `${promptStart} Refine the following skill so it sounds more specific and professional for a ${jobTitle} resume, without changing its meaning: ${currentText} The current skills are: ${array.join(
                ", "
            )}. Do not make this skill a duplicate of any of them. ${promptEnd}`;

        case "skillCategory":
            return `${promptStart} Refine the following skill category so it is clear, professional, and able to group multiple related skills under it: ${currentText} The current categories are: ${array
                .map((obj) => obj.category)
                .join(
                    ", "
                )}. Do not change it into a duplicate of any existing category. Return only the category name text. ${promptEndCategory}`;

        case "skillCategorySkill":
            return `${promptStart} Refine the following skill that belongs to the category ${
                array[0]
            } so it sounds more specific and resume-appropriate, without changing the underlying idea: ${currentText} The current skills in this category are: ${array
                .slice(1)
                .join(
                    ", "
                )}. Do not turn it into a duplicate of any of them. ${promptEndCategory}`;

        case "projectSummary":
            return `${promptStart} Improve the following project description so it sounds more professional and impact-focused. Clarify what the project accomplished and why it matters, and use concise, concrete wording: ${currentText} ${promptEnd}`;

        case "body":
            return `${promptStart} Improve the following cover letter body so it reads smoothly, connects the candidate's experience to the role more clearly, and maintains a confident but approachable tone in the first person. Keep the existing structure of paragraphs and continue to use two newline characters between paragraphs: ${currentText} ${promptEnd}`;

        default:
            return "";
    }
};

export const getPrompt = (data: {
    promptId: string;
    document: any;
    generate: boolean;
    enhance: boolean;
    length: number;
    positionTitle: string;
    array: any[];
    currentText?: string;
}) => {
    const {
        promptId,
        document,
        generate,
        enhance,
        length,
        positionTitle,
        array,
    } = data;
    let jobTitle = document?.information.jobTitle;
    if (generate) {
        return getGeneratePrompt(
            document,
            promptId,
            jobTitle,
            length,
            positionTitle,
            array
        );
    } else if (enhance && data.currentText) {
        return getEnhancePrompt(
            document,
            promptId,
            jobTitle,
            length,
            data.currentText,
            positionTitle,
            array
        );
    }
};
